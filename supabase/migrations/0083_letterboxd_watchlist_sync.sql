-- Letterboxd watchlist sync (lib/letterboxd-watchlist.ts, daily cron).
--
-- `watchlist.from_letterboxd` marks the films Letterboxd decides: a film it lists
-- is claimed, and a claimed film it drops is removed. Films added on the site and
-- never on Letterboxd stay false and the sync leaves them alone. The 445 rows
-- dated before 2026-07-11 came from the Letterboxd CSV export
-- (scripts/backfill-watchlist.mjs), so they start claimed; every site-added row
-- is later than that.
alter table public.watchlist
	add column if not exists from_letterboxd boolean not null default false;

update public.watchlist set from_letterboxd = true where added_at < '2026-07-11';

-- Letterboxd film slug → TMDB movie id, read once from the film page's
