// Side-by-side slots for /subway's Diagram view, from the same bundler as the
// Map view (subway-bundles.mjs): a slot is fixed along each straight and
// shifts only inside a curve. Unlike the map, the SVG offsets every vertex
// itself, so a shift is a smooth slide rather than quarter-slot steps. Reads
// subway-data.js, writes src/scripts/subway-diagram.js (segment id ->
// [x, y, slot] points, schematic coordinates). Run after generate-subway-data.mjs:
//
//   node scripts/generate-subway-diagram.mjs
import { writeFileSync } from "node:fs";
import { SEGMENTS, SERVICES } from "../src/scripts/subway-data.js";
import { sectionLines } from "./subway-bundles.mjs";

// The bundler's thresholds are in metres; here one schematic unit stands in for
// M of them. Parallel services share one centreline exactly, so a large M (tight
// "same track" distance, many membership checks per straight) only sharpens the
// bundles: at 30, the N/Q's few units alongside the R/W at Union Sq counted them in.
const M = 100;

// The schematic leaves a few gaps where a service's segments meet (the N/Q at
// Union Sq and Canal St, up to 7 units). Weld each to the mean of the ends, the
// shift fading out along the segment by arc length — a straight stays straight.
const ends = {}; // "svc|station" -> end points

for (const sg of SEGMENTS) {
  (ends[`${sg.svc}|${sg.a}`] ??= []).push(sg.pts[0]);
  (ends[`${sg.svc}|${sg.b}`] ??= []).push(sg.pts[sg.pts.length - 1]);
}

const mean = (ps) => [0, 1].map((k) => ps.reduce((t, p) => t + p[k], 0) / ps.length);

function weld(sg) {
  const P = sg.pts, last = P.length - 1, wa = mean(ends[`${sg.svc}|${sg.a}`]), wb = mean(ends[`${sg.svc}|${sg.b}`]);
  const da = [wa[0] - P[0][0], wa[1] - P[0][1]], db = [wb[0] - P[last][0], wb[1] - P[last][1]];
  const acc = [0];

  for (let i = 1; i <= last; i++) acc.push(acc[i - 1] + Math.hypot(P[i][0] - P[i - 1][0], P[i][1] - P[i - 1][1]));

  return P.map(([x, y], i) => {
    const t = acc[last] ? acc[i] / acc[last] : 0;

    return [x + da[0] * (1 - t) + db[0] * t, y + da[1] * (1 - t) + db[1] * t];
  });
}

// Left/right per straight, as the diagram always drew it: the earlier service in
// SERVICES order sits south-west of the later one (1/2/3 west to east, 4/5/6 south
// to north). The flip falls on the SW–NE diagonal, which few bundles run along.
const AXIS = [-Math.SQRT1_2, -Math.SQRT1_2]; // y points down: north-west;

const lines = SEGMENTS.map((sg) => ({ sg, pts: weld(sg).map(([x, y]) => [x * M, y * M]) }));

// curveGap: a schematic corner's vertices sit up to ~2 units apart; at 0.6 (60
// "m") a corner broke into pieces and the shift crowded into the first one.
// ease: a station's slot change eases over the whole third of a straight — the
// schematic is small, and 80 "m" would be a few pixels.
const sections = sectionLines(lines, SERVICES.map((s) => s.svc), { ease: Infinity, smooth: true, axis: AXIS, curveGap: 3 * M });

const r2 = (v) => Math.round(v * 100) / 100;

const out = Object.fromEntries(
  Object.entries(sections).map(([id, pts]) => [
    id,
    // drop points under 0.1 units apart: rounded, their edge's direction is noise
    pts
      .map(([x, y, o]) => [r2(x / M), r2(y / M), r2(o)])
      .filter((p, i, all) => i === 0 || i === all.length - 1 || Math.hypot(p[0] - all[i - 1][0], p[1] - all[i - 1][1]) >= 0.1),
  ]),
);

writeFileSync(
  new URL("../src/scripts/subway-diagram.js", import.meta.url),
  "// AUTO-GENERATED by scripts/generate-subway-diagram.mjs: each diagram segment as\n" +
    "// [x, y, slot] points (slot: line spacings right of the direction of travel).\n\n" +
    `export const LINES = ${JSON.stringify(out)};\n`,
);

console.log(`${Object.keys(out).length} segments, ${Object.values(out).flat().length} points`);
